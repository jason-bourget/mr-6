def compress_to_webp(png_bytes, max_width=1280, quality=80):
    """Shrink API PNGs (~2.4 MB) to phone-friendly WebP (~150-250 KB)."""
    from PIL import Image
    im = Image.open(io.BytesIO(png_bytes)).convert("RGB")
    if im.width > max_width:
        im.thumbnail((max_width, max_width * 4))
    out = io.BytesIO()
    im.save(out, format="WEBP", quality=quality, method=6)
    return out.getvalue()


def build_prompt(problem):
    scene = SCENES.get(problem["id"]) or problem.get("imagePrompt") or (
        f"Mr 6 bravely faces {problem['monster']}. {problem['story']}"
    )
    return (f"{CHARACTER_SHEET}\nScene: {scene}\n"
            f"The monster looks impressive but storybook-friendly, not scary.\n{STYLE_SHEET}")


def generate_image(prompt, retries=3):
    last_err = None
    for attempt in range(1, retries + 1):
        req = urllib.request.Request(
            "https://api.openai.com/v1/images/generations",
            data=json.dumps({
                "model": "gpt-image-1",
                "prompt": prompt,
                "size": "1536x1024",
                "quality": args.quality,
                "n": 1,
            }).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {OPENAI_KEY}",
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=600) as res:
                data = json.loads(res.read().decode("utf-8"))
            b64 = (data.get("data") or [{}])[0].get("b64_json")
            if not b64:
                raise RuntimeError("API returned no image data")
            return compress_to_webp(base64.b64decode(b64))
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", errors="replace")[:300]
            last_err = RuntimeError(f"HTTP {e.code}: {body}")
            if e.code in (429, 500, 502, 503) and attempt < retries:
                time.sleep(10 * attempt)
                continue
            raise last_err from None
        except Exception as e:
            last_err = e
            if attempt < retries:
                time.sleep(5 * attempt)
                continue
            raise
    raise last_err


def illustrate(rel):
    path = CONTENT / rel
    problem = json.loads(path.read_text(encoding="utf-8"))
    pid = problem["id"]

    has_webp = (CONTENT / "images" / f"{pid}.webp").exists()
    if not args.force and (has_webp and problem.get("image", "").endswith(".webp")):
        return (pid, "skipped (already has WebP)")
    if args.only and pid != args.only:
        return (pid, None)

    prompt = build_prompt(problem)
    if args.dry_run:
        return (pid, f"DRY RUN prompt:\n{prompt}\n")

    webp = generate_image(prompt)
    image_rel = f"images/{pid}.webp"
    (CONTENT / image_rel).write_bytes(webp)
    problem["image"] = image_rel
    path.write_text(json.dumps(problem, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return (pid, f"OK -> {image_rel} ({len(webp) // 1024} KB)")


def main():
    manifest = json.loads((CONTENT / "manifest.json").read_text(encoding="utf-8"))
    rels = manifest["problems"]
    if args.only:
        rels = [r for r in rels if Path(r).stem == args.only]
        if not rels:
            sys.exit(f"[fail] No problem with id '{args.only}'")

    print(f"[illustrator] {len(rels)} problem(s) to consider - quality: {args.quality}"
          f"{' - DRY RUN' if args.dry_run else ''}")
    done = failed = skipped = 0

    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        futures = {pool.submit(illustrate, rel): rel for rel in rels}
        for fut in as_completed(futures):
            rel = futures[fut]
            try:
                pid, msg = fut.result()
                if msg is None:
                    continue
                if msg.startswith("skipped"):
                    skipped += 1
                else:
                    done += 1
                print(f"  [{pid}] {msg}", flush=True)
            except Exception as err:
                failed += 1
                print(f"  [{Path(rel).stem}] FAILED: {err}", flush=True)

    print(f"\n[done] {done} illustrated, {skipped} skipped, {failed} failed.")
    if failed:
        print("[hint] Re-run the same command — finished images are kept, only missing ones retry.")


if __name__ == "__main__":
    main()
