ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"

parser = argparse.ArgumentParser(description="Generate gpt-image-1 art for Mr 6 adventures")
parser.add_argument("--only", help="illustrate a single problem id")
parser.add_argument("--force", action="store_true", help="regenerate even if a PNG already exists")
parser.add_argument("--quality", default="medium", choices=["low", "medium", "high"])
parser.add_argument("--dry-run", action="store_true", help="print prompts without calling the API")
parser.add_argument("--workers", type=int, default=3, help="parallel requests (default 3)")
args = parser.parse_args()


def key_from_file(name):
    p = ROOT / name
    if p.exists():
        lines = p.read_text(encoding="utf-8").strip().splitlines()
        if lines:
            return lines[0].strip() or None
    return None


OPENAI_KEY = os.environ.get("OPENAI_API_KEY") or key_from_file("openai_apikey.txt")
if not OPENAI_KEY and not args.dry_run:
    sys.exit("[fail] No OpenAI key found — set OPENAI_API_KEY or create openai_apikey.txt.")

