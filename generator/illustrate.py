"""============================================================
Mr 6 — Illustrator
Generates gpt-image-1 artwork for existing problems that still
use SVG/placeholder art, and updates each problem to point at
its new PNG. The original SVGs stay on disk as fallbacks.

Usage:
    python generator/illustrate.py              # illustrate everything without a PNG
    python generator/illustrate.py --only duplicatus-of-the-deep
    python generator/illustrate.py --force      # regenerate PNGs too
    python generator/illustrate.py --quality high
    python generator/illustrate.py --dry-run    # show prompts, no API calls

Key: OPENAI_API_KEY env var or openai_apikey.txt in the project root.
============================================================"""

